/**
 * Given text content, returns the best matching icon component.
 */
export function getIconForContent(text) {
  const lower = text.toLowerCase();
  for (const [keyword, Icon] of Object.entries(ICON_MAP)) {
    if (lower.includes(keyword)) {
      return Icon;
    }
  }
  return null;
}
